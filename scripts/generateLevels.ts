// Generates src/game/levelData.ts: solvable levels, verified by the solver.
// Run: npx tsx scripts/generateLevels.ts
import { writeFileSync } from 'node:fs';
import { CAP, encodeTube } from '../src/game/logic';
import { solve } from '../src/game/solver';

const LEVEL_COUNT = 300;

function mulberry32(seed: number) {
  let a = seed >>> 0;
  return () => {
    a |= 0;
    a = (a + 0x6d2b79f5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

// Bigger levels get more spare (empty) bottles so there is always room to move.
const emptyFor = (colors: number) => (colors <= 6 ? 2 : colors <= 9 ? 3 : 4);

function tier(level: number): { colors: number; empty: number } {
  let colors = 12;
  if (level <= 2) colors = 3;
  else if (level <= 5) colors = 4;
  else if (level <= 10) colors = 5;
  else if (level <= 18) colors = 6;
  else if (level <= 30) colors = 7;
  else if (level <= 48) colors = 8;
  else if (level <= 75) colors = 9;
  else if (level <= 110) colors = 10;
  else if (level <= 160) colors = 11;
  return { colors, empty: emptyFor(colors) };
}

// How many solvable candidates to try per level; the hardest one is kept.
const candidatesFor = (level: number) => (level <= 3 ? 1 : level <= 10 ? 6 : 10);

// Count same-color neighbours inside tubes: fewer = more mixed = harder.
const clumps = (tubes: number[][]) => tubes.reduce((n, t) => n + t.filter((c, i) => i > 0 && c === t[i - 1]).length, 0);

type Out = { tubes: string[]; par: number };
const levels: Out[] = [];
const t0 = Date.now();

for (let level = 1; level <= LEVEL_COUNT; level++) {
  const { colors, empty } = tier(level);
  const rand = mulberry32(level * 7919 + 13);
  const minPar = Math.round(colors * 1.6);
  let made: Out | null = null;
  let bestScore = -Infinity;
  let found = 0;
  const want = candidatesFor(level);
  for (let attempt = 0; attempt < 600 && found < want; attempt++) {
    const palette = Array.from({ length: 12 }, (_, i) => i);
    for (let i = palette.length - 1; i > 0; i--) {
      const j = Math.floor(rand() * (i + 1));
      [palette[i], palette[j]] = [palette[j], palette[i]];
    }
    const used = palette.slice(0, colors);
    const units: number[] = [];
    for (const c of used) for (let k = 0; k < CAP; k++) units.push(c);
    for (let i = units.length - 1; i > 0; i--) {
      const j = Math.floor(rand() * (i + 1));
      [units[i], units[j]] = [units[j], units[i]];
    }
    const tubes: number[][] = [];
    for (let i = 0; i < colors; i++) tubes.push(units.slice(i * CAP, (i + 1) * CAP));
    for (let i = 0; i < empty; i++) tubes.push([]);

    if (tubes.some((t) => t.length === CAP && t.every((x) => x === t[0]))) continue;
    const cl = clumps(tubes);
    // after the tutorial levels, allow at most one same-colour pair on the board
    if (level > 3 && cl > 1) continue;

    const sol = solve(tubes, 90000);
    if (!sol) continue;
    if (sol.length < minPar) continue;
    found++;
    const score = sol.length - 3 * cl;
    if (score > bestScore) {
      bestScore = score;
      made = { tubes: tubes.map(encodeTube), par: sol.length };
    }
  }
  if (!made) throw new Error(`could not generate level ${level}`);
  levels.push(made);
  if (level % 25 === 0) console.log(`level ${level} done (${((Date.now() - t0) / 1000).toFixed(1)}s)`);
}

const body = levels.map((l) => `  { tubes: ${JSON.stringify(l.tubes)}, par: ${l.par} },`).join('\n');
writeFileSync(
  new URL('../src/game/levelData.ts', import.meta.url),
  `// AUTO-GENERATED by scripts/generateLevels.ts - do not edit by hand.\n` +
    `// Every level was verified solvable. Tube strings are base-36 color indices, bottom -> top.\n` +
    `export type LevelDef = { tubes: string[]; par: number };\n` +
    `export const LEVELS: LevelDef[] = [\n${body}\n];\n`,
);
console.log('wrote', levels.length, 'levels');
